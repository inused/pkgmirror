func TestExactReqs(t *testing.T) {
	// 全精确（含注释、空行、marker）→ 解析成功
	reqs := exactReqs([]string{"six==1.17.0", "", "# comment", "requests == 2.34.2 ; python_version >= '3.8'", "--index-url https://x"})
	want := []pypi.Req{{Name: "six", Version: "1.17.0"}, {Name: "requests", Version: "2.34.2"}}
	if !reflect.DeepEqual(reqs, want) {
		t.Errorf("精确解析错误: %+v", reqs)
	}
	// 存在裸包名 → nil（需 uv）
	if reqs := exactReqs([]string{"six==1.0", "lodash"}); reqs != nil {
		t.Errorf("裸包名应返回 nil: %+v", reqs)
	}
	// 版本范围 → nil
	if reqs := exactReqs([]string{"six>=1.0"}); reqs != nil {
		t.Errorf("版本范围应返回 nil: %+v", reqs)
	}
	// == 一侧为空 → nil
	if reqs := exactReqs([]string{"six=="}); reqs != nil {
		t.Errorf("空版本应返回 nil: %+v", reqs)
	}
}

func TestSplitNpmSpec(t *testing.T) {
	cases := []struct {
		in, name, rng string
	}{
		{"lodash", "lodash", ""},
		{"lodash@4", "lodash", "4"},
		{"lodash@^4.17.0", "lodash", "^4.17.0"},
		{"@babel/core", "@babel/core", ""},
		{"@babel/core@^7", "@babel/core", "^7"},
		{"@scope/pkg@1.2.3-beta.1", "@scope/pkg", "1.2.3-beta.1"},
	}
	for _, c := range cases {
		name, rng := splitNpmSpec(c.in)
		if name != c.name || rng != c.rng {
			t.Errorf("splitNpmSpec(%q) = (%q,%q), 期望 (%q,%q)", c.in, name, rng, c.name, c.rng)
		}
	}
}

