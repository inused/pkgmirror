func TestDetectReqFile(t *testing.T) {
	dir := t.TempDir()
	write := func(name, content string) string {
		path := filepath.Join(dir, name)
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
		return path
	}
	if kind, err := detectReqFile(write("lock.json", `{"lockfileVersion":3,"packages":{}}`)); err != nil || kind != "lock" {
		t.Errorf("lock 识别错误: %s %v", kind, err)
	}
	if kind, err := detectReqFile(write("pkg.json", `{"name":"x","dependencies":{"lodash":"^4"}}`)); err != nil || kind != "manifest" {
		t.Errorf("package.json 识别错误: %s %v", kind, err)
	}
	// yarn.lock / pnpm-lock.yaml 等非 JSON 给出转换指引
	if _, err := detectReqFile(write("yarn.lock", "# THIS IS AN AUTOGENERATED FILE...\nlodash@^4:")); err == nil {
		t.Error("非 JSON 应报错")
	} else if want := "npm install --package-lock-only"; !strings.Contains(err.Error(), want) {
		t.Errorf("错误信息应包含转换指引 %q: %v", want, err)
	}
	// 既无 lockfileVersion 也无 dependencies
	if _, err := detectReqFile(write("empty.json", `{"name":"x"}`)); err == nil {
		t.Error("无法识别的 JSON 应报错")
	}
}

// TestFetchAndRecordNode 验证 node/ 前缀文件的清单登记：Type/Tag 取自
// 版本目录，源不提供哈希时（SHASUMS256.txt 本身）登记实际计算的哈希。
func TestFetchAndRecordNode(t *testing.T) {
	ts := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		io.WriteString(w, "abc123\n")
	}))
	defer ts.Close()

	out := t.TempDir()
	mf := newManifest("test")
	client := ts.Client()

	// SHASUMS256.txt：源无哈希，登记时应计算实际哈希
	dest := filepath.Join(out, "node", "v22.14.0", "SHASUMS256.txt")
	if err := fetchAndRecord(context.Background(), client, ts.URL+"/v22.14.0/SHASUMS256.txt", dest, "", out, &mf); err != nil {
		t.Fatal(err)
	}
	// 归档：按源提供的哈希校验并登记
	arch := filepath.Join(out, "node", "v22.14.0", "node-v22.14.0-linux-x64.tar.xz")
	sum := sha256.Sum256([]byte("abc123\n"))
	if err := fetchAndRecord(context.Background(), client, ts.URL+"/v22.14.0/node-v22.14.0-linux-x64.tar.xz", arch, hex.EncodeToString(sum[:]), out, &mf); err != nil {
		t.Fatal(err)
	}
	// 重复登记同一路径去重
	if err := fetchAndRecord(context.Background(), client, ts.URL+"/v22.14.0/SHASUMS256.txt", dest, "", out, &mf); err != nil {
		t.Fatal(err)
	}

	if len(mf.Files) != 2 {
		t.Fatalf("清单应 2 条，实际 %d: %+v", len(mf.Files), mf.Files)
	}
	for _, f := range mf.Files {
		if f.Type != "node" || f.Tag != "v22.14.0" {
			t.Fatalf("node 条目 Type/Tag 错误: %+v", f)
		}
		if f.SHA256 == "" {
			t.Fatalf("node 条目缺哈希: %+v", f)
		}
	}
	// 清单可被 manifest.Load 接受（契约校验通过）
	if err := manifest.Save(out, mf); err != nil {
		t.Fatal(err)
	}
	if _, err := manifest.Load(out); err != nil {
		t.Fatalf("清单应通过契约校验: %v", err)
	}
}

func TestResolveGoProxy(t *testing.T) {
	// 命令行 > 配置 > 环境；GOPROXY 形式的值取首个 URL 段、忽略 direct
	os.Setenv("GOPROXY", "https://goproxy.cn,https://proxy.golang.org,direct")
	defer os.Unsetenv("GOPROXY")
	if got := ResolveGoProxy("", ""); got != "https://goproxy.cn" {
		t.Errorf("环境变量兜底 = %q，应为 https://goproxy.cn", got)
	}
	if got := ResolveGoProxy("https://a.cn/", ""); got != "https://a.cn" {
		t.Errorf("命令行优先且去尾斜杠 = %q", got)
	}
	if got := ResolveGoProxy("", "https://b.cn"); got != "https://b.cn" {
		t.Errorf("配置优先于环境 = %q", got)
	}
	// 全为 direct/off 时落官方默认
	os.Setenv("GOPROXY", "direct")
	if got := ResolveGoProxy("", ""); got != DefaultGoProxy {
		t.Errorf("direct-only 环境 = %q，应为官方默认", got)
	}
}

func TestSplitGoRefs(t *testing.T) {
	// go.sum + 命令行条目：精确进静态集合，裸名/@latest/前缀进待解析引用
	dir := t.TempDir()
	sum := "github.com/spf13/cobra v1.8.1 h1:x=\ngithub.com/spf13/cobra v1.8.1/go.mod h1:y=\nexample.com/b v2.0.0+incompatible h1:z=\n"
	path := filepath.Join(dir, "go.sum")
	os.WriteFile(path, []byte(sum), 0o644)
	refs, static, err := splitGoRefs(DownloadGomodOptions{GoSumFile: path, Modules: []string{
		"example.com/a",                 // 裸名 → latest
		"example.com/c@latest",          // 显式 latest
		"example.com/d@v1.8",            // minor 前缀
		"example.com/a@v1.0.0",          // 精确（与裸名同名不同版本，允许并存）
		"github.com/spf13/cobra@v1.8.1", // 精确重复，去重
	}})
	if err != nil {
		t.Fatal(err)
	}
	if len(static) != 3 {
		t.Fatalf("静态目标应 3 个（go.sum 两模块 + 精确 a@v1.0.0），得到 %+v", static)
	}
	wantStatic := []string{"example.com/a@v1.0.0", "example.com/b@v2.0.0+incompatible", "github.com/spf13/cobra@v1.8.1"}
	for i, mv := range static {
		if got := mv.Module + "@" + mv.Version; got != wantStatic[i] {
			t.Errorf("静态第 %d = %s，应为 %s", i, got, wantStatic[i])
		}
	}
	if len(refs) != 3 {
		t.Fatalf("待解析引用应 3 个，得到 %+v", refs)
	}
	for i, want := range []string{"", "latest", "v1.8"} {
		if refs[i].Ref != want {
			t.Errorf("引用第 %d = %+v，Ref 应为 %q", i, refs[i], want)
		}
	}
	// 非法引用（裸名是合法形式，会走 @latest 解析，由上游 404 报模块不存在）
	for _, bad := range []string{"../evil@v1.0.0", "bad name@v1.0.0"} {
		if _, _, err := splitGoRefs(DownloadGomodOptions{Modules: []string{bad}}); err == nil {
			t.Errorf("非法条目 %q 应报错", bad)
		}
	}
	if _, _, err := splitGoRefs(DownloadGomodOptions{Modules: []string{"m@^1.2"}}); err == nil {
		t.Error("semver range 引用应报错（支持 latest/前缀/精确）")
	}
	// 空输入返回双空
	refs, static, err = splitGoRefs(DownloadGomodOptions{})
	if err != nil || len(refs) != 0 || len(static) != 0 {
		t.Errorf("空输入应得双空集合: %+v %+v %v", refs, static, err)
	}
}

func TestResolveGoRef(t *testing.T) {
	// httptest 模拟上游 proxy 的 @latest 与 @v/list 端点
	mux := http.NewServeMux()
	mux.HandleFunc("/example.com/a/@latest", func(w http.ResponseWriter, r *http.Request) {
		io.WriteString(w, `{"Version":"v1.10.0","Time":"2026-01-01T00:00:00Z"}`)
	})
	mux.HandleFunc("/example.com/d/@v/list", func(w http.ResponseWriter, r *http.Request) {
		io.WriteString(w, "v2.0.0-rc1\nv1.9.2\nv1.8.0\nv1.8.3-rc1\nv1.8.1\n")
	})
	mux.HandleFunc("/example.com/nope/@latest", func(w http.ResponseWriter, r *http.Request) {
		http.NotFound(w, r)
	})
	srv := httptest.NewServer(mux)
	defer srv.Close()
	ctx := context.Background()

	// 裸名与 latest 等价：取 @latest 的 Version
	for _, ref := range []string{"", "latest"} {
		ver, err := resolveGoRef(ctx, srv.Client(), srv.URL, goRef{Module: "example.com/a", Ref: ref})
		if err != nil || ver != "v1.10.0" {
			t.Errorf("resolve(%q) = %q, %v，应为 v1.10.0", ref, ver, err)
		}
	}
	// minor 前缀：取该线最新稳定版（排除 rc）
	ver, err := resolveGoRef(ctx, srv.Client(), srv.URL, goRef{Module: "example.com/d", Ref: "v1.8"})
	if err != nil || ver != "v1.8.1" {
		t.Errorf("v1.8 前缀 = %q, %v，应为 v1.8.1", ver, err)
	}
	// 无匹配前缀报错
	if _, err := resolveGoRef(ctx, srv.Client(), srv.URL, goRef{Module: "example.com/d", Ref: "v3"}); err == nil {
		t.Error("无 v3 前缀应报错")
	}
	// 模块不存在
	if _, err := resolveGoRef(ctx, srv.Client(), srv.URL, goRef{Module: "example.com/nope"}); err == nil {
		t.Error("不存在的模块应报错")
	}
}

// TestRunDelete 覆盖客户端删除流程：先 dry-run 后执行两次请求的语义
// 与服务端错误的传播。
func TestRunDelete(t *testing.T) {
	var bodies []string
	ts := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		body, _ := io.ReadAll(r.Body)
		bodies = append(bodies, string(body))
		switch string(body) {
		case `{"type":"pypi","name":"six","deps":true,"dryRun":true}`:
			io.WriteString(w, `{"status":"preview","targets":[{"name":"six","files":[{"path":"pypi/six/a.whl","size":10}],"size":10}],"cascades":[{"name":"idna","files":[{"path":"pypi/idna/b.whl","size":5}],"size":5}],"count":2,"total":15}`)
		case `{"type":"pypi","name":"six","deps":true,"dryRun":false}`:
			io.WriteString(w, `{"status":"ok","targets":[{"name":"six","files":[{"path":"pypi/six/a.whl","size":10}],"size":10}],"cascades":[{"name":"idna","files":[{"path":"pypi/idna/b.whl","size":5}],"size":5}],"count":2,"total":15}`)
		default:
			http.Error(w, "pypi six 不存在", http.StatusNotFound)
		}
	}))
	t.Cleanup(ts.Close)

	if err := RunDelete(DeleteOptions{Type: "pypi", Name: "six", Deps: true, Yes: true, Server: ts.URL}); err != nil {
		t.Fatalf("删除失败: %v", err)
	}
	if len(bodies) != 2 {
		t.Fatalf("应发起 dry-run 与执行两次请求, 发起 %d 次", len(bodies))
	}
	if bodies[0] != `{"type":"pypi","name":"six","deps":true,"dryRun":true}` || bodies[1] != `{"type":"pypi","name":"six","deps":true,"dryRun":false}` {
		t.Errorf("请求体顺序或内容错误: %v", bodies)
	}

	// 目标不存在：404 与服务端错误文本原样传播
	err := RunDelete(DeleteOptions{Type: "pypi", Name: "nope", Yes: true, Server: ts.URL})
	if err == nil || !strings.Contains(err.Error(), "404") || !strings.Contains(err.Error(), "不存在") {
		t.Errorf("404 应原样传播, 得到 %v", err)
	}
}

func TestMatchDists(t *testing.T) {
	files := []pypi.File{
		{Filename: "demo-1.0-py3-none-any.whl", Yanked: true, YankedReason: "broken wheel"},
		{Filename: "demo-1.0.tar.gz"},
		{Filename: "demo-1.0-cp311-cp311-manylinux_2_17_x86_64.whl"},
		{Filename: "demo-0.9.tar.gz"},
	}
	req := pypi.Req{Name: "demo", Version: "1.0"}

	// 有非撤回文件时必须忽略撤回文件（PEP 592 MUST 条款）
	got := matchDists(files, req, []int{11, 12}, nil, nil, false)
	if len(got) != 2 {
		t.Fatalf("排除撤回后命中 %d 个文件, 期望 2（sdist 与兼容 wheel）: %+v", len(got), got)
	}
	if got[0].Filename != "demo-1.0.tar.gz" || got[1].Filename != "demo-1.0-cp311-cp311-manylinux_2_17_x86_64.whl" {
		t.Errorf("命中文件错误: %+v", got)
	}

	// includeYanked=true 保留撤回文件，供仅撤回文件匹配时回退
	got = matchDists(files, req, []int{11, 12}, nil, nil, true)
	if len(got) != 3 || !got[0].Yanked {
		t.Errorf("回退模式应包含撤回文件: %+v", got)
	}

	// 版本不符一律排除
	got = matchDists(files, pypi.Req{Name: "demo", Version: "0.9"}, []int{12}, nil, nil, true)
	if len(got) != 1 || got[0].Filename != "demo-0.9.tar.gz" {
		t.Errorf("0.9 应只命中自身 sdist: %+v", got)
	}

	// wheel 不兼容目标 Python 版本时仅剩 sdist
	got = matchDists(files, req, []int{13}, nil, nil, true)
	if len(got) != 2 {
		t.Fatalf("Python 3.13 应排除 cp311 非 abi3 wheel: %+v", got)
	}
	for _, f := range got {
		if f.Filename == "demo-1.0-cp311-cp311-manylinux_2_17_x86_64.whl" {
			t.Errorf("cp311 wheel 不应命中 3.13: %+v", got)
		}
	}
}
