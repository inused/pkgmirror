func TestExactReqs(t *testing.T) {
	// 全精确（含注释、空行、marker）→ 解析成功
	reqs := exactReqs([]string{"six==1.17.0", "", "# comment", "requests == 2.34.2 ; python_version >= '3.8'", "--index-url https://x"})
	want := []pypi.Req{{Name: "six", Version: "1.17.0"}, {Name: "requests", Version: "2.34.2"}}
	if !reflect.DeepEqual(reqs, want) {
		t.Errorf("精确解析错误: %+v", reqs)
	}
	// 存在裸包名 → nil（需 uv）
	if reqs := exactReqs([]string{"six==1.0", "lodash"}); reqs != nil {
		t.Errorf("裸包名应返回 nil: %+v", reqs)
	}
	// 版本范围 → nil
	if reqs := exactReqs([]string{"six>=1.0"}); reqs != nil {
		t.Errorf("版本范围应返回 nil: %+v", reqs)
	}
	// == 一侧为空 → nil
	if reqs := exactReqs([]string{"six=="}); reqs != nil {
		t.Errorf("空版本应返回 nil: %+v", reqs)
	}
}

func TestSplitNpmSpec(t *testing.T) {
	cases := []struct {
		in, name, rng string
	}{
		{"lodash", "lodash", ""},
		{"lodash@4", "lodash", "4"},
		{"lodash@^4.17.0", "lodash", "^4.17.0"},
		{"@babel/core", "@babel/core", ""},
		{"@babel/core@^7", "@babel/core", "^7"},
		{"@scope/pkg@1.2.3-beta.1", "@scope/pkg", "1.2.3-beta.1"},
	}
	for _, c := range cases {
		name, rng := splitNpmSpec(c.in)
		if name != c.name || rng != c.rng {
			t.Errorf("splitNpmSpec(%q) = (%q,%q), 期望 (%q,%q)", c.in, name, rng, c.name, c.rng)
		}
	}
}

func TestParseNodeVersion(t *testing.T) {
	cases := []struct {
		in, want string
	}{
		{"18", "18.0.0"},
		{"18.20", "18.20.0"},
		{"18.20.1", "18.20.1"},
	}
	for _, c := range cases {
		got, err := ParseNodeVersion(c.in)
		if err != nil || got != c.want {
			t.Errorf("ParseNodeVersion(%q) = %q,%v, 期望 %q", c.in, got, err, c.want)
		}
	}
	for _, bad := range []string{"", "x", "18.20.1.2", "18-beta"} {
		if _, err := ParseNodeVersion(bad); err == nil {
			t.Errorf("ParseNodeVersion(%q) 应报错", bad)
		}
	}
}

func TestDetectReqFile(t *testing.T) {
	dir := t.TempDir()
	write := func(name, content string) string {
		path := filepath.Join(dir, name)
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
		return path
	}
	if kind, err := detectReqFile(write("lock.json", `{"lockfileVersion":3,"packages":{}}`)); err != nil || kind != "lock" {
		t.Errorf("lock 识别错误: %s %v", kind, err)
	}
	if kind, err := detectReqFile(write("pkg.json", `{"name":"x","dependencies":{"lodash":"^4"}}`)); err != nil || kind != "manifest" {
		t.Errorf("package.json 识别错误: %s %v", kind, err)
	}
	// yarn.lock / pnpm-lock.yaml 等非 JSON 给出转换指引
	if _, err := detectReqFile(write("yarn.lock", "# THIS IS AN AUTOGENERATED FILE...\nlodash@^4:")); err == nil {
		t.Error("非 JSON 应报错")
	} else if want := "npm install --package-lock-only"; !strings.Contains(err.Error(), want) {
		t.Errorf("错误信息应包含转换指引 %q: %v", want, err)
	}
	// 既无 lockfileVersion 也无 dependencies
	if _, err := detectReqFile(write("empty.json", `{"name":"x"}`)); err == nil {
		t.Error("无法识别的 JSON 应报错")
	}
}

// TestFetchAndRecordNode 验证 node/ 前缀文件的清单登记：Type/Tag 取自
// 版本目录，源不提供哈希时（SHASUMS256.txt 本身）登记实际计算的哈希。
func TestFetchAndRecordNode(t *testing.T) {
	ts := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		io.WriteString(w, "abc123\n")
	}))
	defer ts.Close()

	out := t.TempDir()
	mf := newManifest("test")
	client := ts.Client()

	// SHASUMS256.txt：源无哈希，登记时应计算实际哈希
	dest := filepath.Join(out, "node", "v22.14.0", "SHASUMS256.txt")
	if err := fetchAndRecord(context.Background(), client, ts.URL+"/v22.14.0/SHASUMS256.txt", dest, "", out, &mf); err != nil {
		t.Fatal(err)
	}
	// 归档：按源提供的哈希校验并登记
	arch := filepath.Join(out, "node", "v22.14.0", "node-v22.14.0-linux-x64.tar.xz")
	sum := sha256.Sum256([]byte("abc123\n"))
	if err := fetchAndRecord(context.Background(), client, ts.URL+"/v22.14.0/node-v22.14.0-linux-x64.tar.xz", arch, hex.EncodeToString(sum[:]), out, &mf); err != nil {
		t.Fatal(err)
	}
	// 重复登记同一路径去重
	if err := fetchAndRecord(context.Background(), client, ts.URL+"/v22.14.0/SHASUMS256.txt", dest, "", out, &mf); err != nil {
		t.Fatal(err)
	}

	if len(mf.Files) != 2 {
		t.Fatalf("清单应 2 条，实际 %d: %+v", len(mf.Files), mf.Files)
	}
	for _, f := range mf.Files {
		if f.Type != "node" || f.Tag != "v22.14.0" {
			t.Fatalf("node 条目 Type/Tag 错误: %+v", f)
		}
		if f.SHA256 == "" {
			t.Fatalf("node 条目缺哈希: %+v", f)
		}
	}
	// 清单可被 manifest.Load 接受（契约校验通过）
	if err := manifest.Save(out, mf); err != nil {
		t.Fatal(err)
	}
	if _, err := manifest.Load(out); err != nil {
		t.Fatalf("清单应通过契约校验: %v", err)
	}
}
