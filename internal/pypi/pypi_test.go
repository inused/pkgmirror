func TestParseSimpleHTML(t *testing.T) {
	html := `<!DOCTYPE html><html><body>
<h1>Links for requests</h1>
<a href="/packages/requests/requests-2.31.0-py3-none-any.whl#sha256=abc123">requests-2.31.0-py3-none-any.whl</a><br/>
<a href="/packages/requests/requests-2.31.0.tar.gz">requests-2.31.0.tar.gz</a><br/>
</body></html>`
	files := parseSimpleHTML("https://pypi.org/simple/requests/", []byte(html))
	if len(files) != 2 {
		t.Fatalf("提取到 %d 个文件, 期望 2", len(files))
	}
	if files[0].Filename != "requests-2.31.0-py3-none-any.whl" || files[0].SHA256 != "abc123" {
		t.Errorf("第一个文件解析错误: %+v", files[0])
	}
	if files[1].SHA256 != "" {
		t.Errorf("无哈希链接的 sha256 应为空: %+v", files[1])
	}
}

func TestWheelMatchesPython(t *testing.T) {
	cases := []struct {
		filename string
		minors   []int
		want     bool
	}{
		// 纯 Python：py2.py3 含 py3，兼容全部 3.x
		{"six-1.17.0-py2.py3-none-any.whl", []int{11}, true},
		// 精确解释器标签
		{"numpy-1.26.4-cp312-cp312-manylinux_2_17_x86_64.whl", []int{12}, true},
		{"numpy-1.26.4-cp312-cp312-manylinux_2_17_x86_64.whl", []int{11}, false},
		{"numpy-1.26.4-cp312-cp312-manylinux_2_17_x86_64.whl", []int{11, 12}, true},
		// abi3 向后兼容：cp311-abi3 可用于 3.12
		{"foo-1.0-cp311-abi3-manylinux_2_17_x86_64.whl", []int{12}, true},
		// abi3 只向后兼容：cp313-abi3 不能用于 3.12
		{"foo-1.0-cp313-abi3-manylinux_2_17_x86_64.whl", []int{12}, false},
		// py2 不兼容 3.x
		{"old-1.0-py2-none-any.whl", []int{12}, false},
		// py3 通用
		{"pure-1.0-py3-none-any.whl", []int{9}, true},
	}
	for _, c := range cases {
		if got := WheelMatchesPython(c.filename, c.minors); got != c.want {
			t.Errorf("WheelMatchesPython(%q, %v) = %v, 期望 %v", c.filename, c.minors, got, c.want)
		}
	}
}

func TestWheelMatchesPlatformArch(t *testing.T) {
	linuxX8664 := "numpy-1.26.4-cp312-cp312-manylinux_2_17_x86_64.whl"
	winAmd64 := "pillow-10.0.0-cp312-cp312-win_amd64.whl"
	win32 := "pkg-1.0-cp312-cp312-win32.whl"
	macArm := "pkg-1.0-cp312-cp312-macosx_11_0_arm64.whl"
	muslArm := "pkg-1.0-cp312-cp312-musllinux_1_1_aarch64.whl"
	anyWhl := "six-1.17.0-py3-none-any.whl"
	// 复合平台标签：同时支持 manylinux x86_64 与 macOS arm64
	combo := "pkg-1.0-cp312-cp312-manylinux_2_17_x86_64.macosx_11_0_arm64.whl"

	cases := []struct {
		filename  string
		platforms []string
		archs     []string
		want      bool
	}{
		{anyWhl, []string{"windows"}, nil, true}, // any 恒匹配
		{linuxX8664, []string{"linux"}, nil, true},
		{linuxX8664, []string{"windows"}, nil, false},
		{linuxX8664, nil, []string{"x86_64"}, true},
		{linuxX8664, nil, []string{"aarch64"}, false},
		{linuxX8664, []string{"linux"}, []string{"aarch64"}, false},
		{winAmd64, []string{"windows"}, []string{"x86_64"}, true}, // amd64 是 x86_64 别名
		{win32, []string{"windows"}, []string{"i686"}, true},      // win32 即 32 位
		{win32, []string{"windows"}, []string{"x86_64"}, false},
		{macArm, []string{"darwin"}, []string{"arm64"}, true},
		{macArm, []string{"darwin"}, []string{"x86_64"}, false},
		{muslArm, []string{"linux"}, []string{"aarch64"}, true}, // musllinux 属 linux
		{combo, []string{"darwin"}, []string{"arm64"}, true},    // 复合标签任一命中即可
		{combo, []string{"linux"}, []string{"x86_64"}, true},
		{combo, []string{"windows"}, nil, false},
	}
	for _, c := range cases {
		if got := WheelMatchesPlatformArch(c.filename, c.platforms, c.archs); got != c.want {
			t.Errorf("WheelMatchesPlatformArch(%q, %v, %v) = %v, 期望 %v",
				c.filename, c.platforms, c.archs, got, c.want)
		}
	}
}

// TestDepNamesFromArchive 覆盖 wheel / sdist tar / sdist zip 三种元数据
// 形态与无元数据的空结果。
func TestDepNamesFromArchive(t *testing.T) {
	meta := "Metadata-Version: 2.1\nName: req\nRequires-Dist: idna (>=2.5,<4)\nRequires-Dist: urllib3<3\nRequires-Dist: pysocks (!=1.5.7) ; extra == 'socks'\n\n正文区不解析\n"
	dir := t.TempDir()

	// wheel：zip 内 *.dist-info/METADATA
	var wz bytes.Buffer
	zw := zip.NewWriter(&wz)
	fw, _ := zw.Create("req-2.0.dist-info/METADATA")
	fw.Write([]byte(meta))
	zw.Close()
	whl := filepath.Join(dir, "req-2.0-py3-none-any.whl")
	os.WriteFile(whl, wz.Bytes(), 0o644)

	// sdist tar.gz：内层目录 PKG-INFO
	var tg bytes.Buffer
	gzw := gzip.NewWriter(&tg)
	tw := tar.NewWriter(gzw)
	tw.WriteHeader(&tar.Header{Name: "req-2.0/PKG-INFO", Mode: 0o644, Size: int64(len(meta))})
	tw.Write([]byte(meta))
	tw.Close()
	gzw.Close()
	tgz := filepath.Join(dir, "req-2.0.tar.gz")
	os.WriteFile(tgz, tg.Bytes(), 0o644)

	// sdist zip：根 PKG-INFO（无内层目录）
	var sz bytes.Buffer
	zs := zip.NewWriter(&sz)
	f2, _ := zs.Create("req-2.0/PKG-INFO")
	f2.Write([]byte(meta))
	zs.Close()
	szip := filepath.Join(dir, "req-2.0.zip")
	os.WriteFile(szip, sz.Bytes(), 0o644)

	want := []string{"idna", "pysocks", "urllib3"}
	for _, path := range []string{whl, tgz, szip} {
		got, err := DepNamesFromArchive(path)
		if err != nil {
			t.Fatalf("%s: 解析失败: %v", path, err)
		}
		if !reflect.DeepEqual(got, want) {
			t.Errorf("%s: 依赖名 = %v, want %v", path, got, want)
		}
	}

	// 无元数据条目的 wheel 与未知扩展名 → 空
	var bare bytes.Buffer
	bw := zip.NewWriter(&bare)
	bw.Create("req-2.0.dist-info/WHEEL")
	bw.Close()
	bareWhl := filepath.Join(dir, "bare-1.0-py3-none-any.whl")
	os.WriteFile(bareWhl, bare.Bytes(), 0o644)
	if got, _ := DepNamesFromArchive(bareWhl); len(got) != 0 {
		t.Errorf("无 METADATA 的 wheel 应无依赖, 得到 %v", got)
	}
	if got, _ := DepNamesFromArchive(filepath.Join(dir, "x.txt")); got != nil {
		t.Errorf("未知扩展名应返回空, 得到 %v", got)
	}
}
